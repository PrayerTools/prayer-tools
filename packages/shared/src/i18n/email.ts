export const EMAIL_STRINGS: Record<string, EmailStrings> = { en, es, fr, pt, ar }

export function emailT(lang: string, key: string, vars: Record<string, string | number> = {}): string {
  const s = EMAIL_STRINGS[lang]?.[key] ?? en[key] ?? key
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m))
}
